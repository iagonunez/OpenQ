"""Generate THIRD_PARTY_LICENSES.md: every Rust crate compiled into OpenQ (all targets, normal
dependencies) with its licence, plus the full licence texts each crate ships, deduplicated.

Usage (from the repository root): python3 -I tools/third_party_licenses.py
Re-run after changing dependencies.
"""
import hashlib
import json
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parent.parent
meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--format-version", "1", "--locked"], cwd=root, check=True, capture_output=True, text=True,
).stdout)
tree = subprocess.run(
    ["cargo", "tree", "--locked", "--target", "all", "-e", "normal", "--prefix", "none", "--format", "{p}"],
    cwd=root, check=True, capture_output=True, text=True,
).stdout
used = set()
for line in tree.splitlines():
    m = re.match(r"(\S+) v(\S+)", line.strip())
    if m and m.group(1) != "openq":
        used.add((m.group(1), m.group(2)))

LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|copyright|notice|unlicense|ofl|ufl)([-_.].*)?$", re.I)
packages = sorted(
    (p for p in meta["packages"] if (p["name"], p["version"]) in used),
    key=lambda p: (p["name"].lower(), p["version"]),
)

texts = {}  # hash -> (text, [crate ids])
rows = []
for p in packages:
    pid = f'{p["name"]} {p["version"]}'
    pdir = pathlib.Path(p["manifest_path"]).parent
    files = [f for f in sorted(pdir.iterdir()) if f.is_file() and LICENSE_FILE.match(f.name)]
    if p["name"] == "epaint_default_fonts":  # fonts compiled into the binary
        files += sorted((pdir / "fonts").glob("*.txt"))
    if p.get("license_file"):
        lf = pdir / p["license_file"]
        if lf.is_file() and lf not in files:
            files.append(lf)
    hashes = []
    for f in files:
        text = f.read_text(errors="replace").strip()
        if not text:
            continue
        h = hashlib.sha256(text.encode()).hexdigest()[:12]
        texts.setdefault(h, (f.name, text, []))[2].append(pid)
        hashes.append(h)
    if not hashes:
        # No licence file in the crate: attach the standard text of its (first-choice) SPDX licence.
        spdx = re.split(r"\s+OR\s+|/", (p.get("license") or "").strip("()"))[0].strip()
        std = root / "tools" / "licenses" / f"{spdx}.txt"
        if std.is_file():
            text = std.read_text().strip()
            h = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(h, (f"{spdx} (standard text)", text, []))[2].append(pid)
            hashes.append(h)
    rows.append((p, hashes))

out = ["# Third-party licences", "",
       "OpenQ is built from the Rust crates below (all platforms, normal dependencies). Each keeps its own",
       "licence; where a crate offers a choice (\"MIT OR Apache-2.0\"), OpenQ uses it under either.",
       "The full texts the crates ship follow the table, each listed once with the crates that use it.",
       "Generated by `tools/third_party_licenses.py` — do not edit by hand.", "",
       f"{len(rows)} crates.", "",
       "| Crate | Version | Licence | Source | Texts |", "|---|---|---|---|---|"]
for p, hashes in rows:
    src = p.get("repository") or f'https://crates.io/crates/{p["name"]}'
    refs = " ".join(f"[{h[:6]}](#t-{h})" for h in dict.fromkeys(hashes)) or "see SPDX licence"
    out.append(f'| {p["name"]} | {p["version"]} | {p.get("license") or "see file"} | <{src}> | {refs} |')
out += ["", "## Licence texts", ""]
for h, (name, text, users) in sorted(texts.items(), key=lambda kv: (kv[1][0].lower(), kv[0])):
    out += [f'<a id="t-{h}"></a>', f"### {name} ({h[:6]})", "",
            "Used by: " + ", ".join(dict.fromkeys(users)), "", "```text", text.replace("```", "'''"), "```", ""]
(root / "THIRD_PARTY_LICENSES.md").write_text("\n".join(out) + "\n")
print(f"{len(rows)} crates, {len(texts)} distinct licence texts")
missing = [f'{p["name"]} {p["version"]} ({p.get("license")})' for p, h in rows if not h]
if missing:
    print("crates without a licence file (covered by their SPDX licence):", ", ".join(missing))
