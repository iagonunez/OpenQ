"""Build the subset fonts in assets/fonts and src/ui/icons.rs.

Usage: python3 -I tools/build_fonts.py <download-dir>
where <download-dir> contains the upstream files:
  MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf / .codepoints  (Apache-2.0, google/material-design-icons)
  Inter[opsz,wght].ttf                                             (OFL, google/fonts)
  JetBrainsMono[wght].ttf                                          (OFL, google/fonts)
  BarlowCondensed-SemiBold.ttf                                     (OFL, google/fonts)
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools import subset

src = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
out = root / "assets" / "fonts"
out.mkdir(parents=True, exist_ok=True)

names = [l.strip() for l in (root / "tools" / "icons.txt").read_text().splitlines() if l.strip() and not l.startswith("#")]
cps = {}
for line in (src / "MaterialSymbolsRounded[FILL,GRAD,opsz,wght].codepoints").read_text().splitlines():
    n, cp = line.split()
    cps[n] = int(cp, 16)
missing = [n for n in names if n not in cps]
if missing:
    sys.exit(f"unknown icons: {missing}")


def build(path, axes, unicodes, dest):
    f = TTFont(path)
    if axes:
        f = instantiateVariableFont(f, axes)
    opts = subset.Options()
    opts.layout_features = ["*"]
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=unicodes)
    s.subset(f)
    f.save(dest)
    print(dest.name, dest.stat().st_size, "bytes")


icon_cps = sorted({cps[n] for n in names})
sym = src / "MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf"
build(sym, {"FILL": 0, "wght": 400, "GRAD": 0, "opsz": 24}, icon_cps, out / "MaterialSymbolsRounded.ttf")
build(sym, {"FILL": 1, "wght": 400, "GRAD": 0, "opsz": 24}, icon_cps, out / "MaterialSymbolsRounded-Filled.ttf")

latin = list(range(0x20, 0x250)) + list(range(0x2000, 0x2070)) + [0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x221E, 0x2026, 0x00D7, 0x2715, 0x25B6]
build(src / "Inter[opsz,wght].ttf", {"wght": 400, "opsz": 14}, latin, out / "Inter-Regular.ttf")
build(src / "Inter[opsz,wght].ttf", {"wght": 600, "opsz": 14}, latin, out / "Inter-SemiBold.ttf")
build(src / "JetBrainsMono[wght].ttf", {"wght": 500}, latin, out / "JetBrainsMono-Medium.ttf")
# Title / branding (static font, OFL).
build(src / "BarlowCondensed-SemiBold.ttf", None, latin, out / "BarlowCondensed-SemiBold.ttf")

rs = ["//! Material Symbols Rounded codepoints (generated by tools/build_fonts.py — do not edit).", "#![allow(dead_code)]", ""]
for n in names:
    rs.append(f'pub const {n.upper()}: &str = "\\u{{{cps[n]:x}}}";')
(root / "src" / "ui" / "icons.rs").write_text("\n".join(rs) + "\n")
print("icons.rs:", len(names), "icons")
